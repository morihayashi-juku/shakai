def apply(S):
    for s in S:
        no = s["no"]
        for p, t in HINTS.get(no, {}).items():
            s["pages"][p].setdefault("kai", []).append(("地図・図のヒント", t))
        for p, h, t in EXTRA.get(no, []):
            s["pages"][p].setdefault("kai", []).append((h, t))
        # 語群（解説のあるページの図だけ。ヒントに【 】が書いてあるものは除く）
        for pg in s["pages"]:
            if not pg.get("kai"):
                continue
            for f in pg.get("figs", []):
                if f.get("q") and "【" not in f.get("hint", "") and not f.get("nobank"):
                    words = []
                    for _, _, a in f["q"]:
                        a = a.split("（")[0] if a.count("（") and not a.startswith("ASEAN") else a
                        if a not in words:
                            words.append(a)
                    words = sorted(words, key=lambda w: (hash_(w), w))
                    f["hint"] = f.get("hint", "") + "<br>【 " + "・".join(words) + " 】"
    return S


def hash_(w):
    return sum(ord(c) * (i + 7) for i, c in enumerate(w)) % 97
