# ［答え］＝書きこむ空らん　［［答え］］＝文で書く欄　{{fig:キー}}＝図
def sec(title, mins, body): return f'<div class="jsec"><h3>{title}<small>目安 {mins}分</small></h3>{body}</div>'
def fig(k, w): return f'<div class="fig" style="width:{w}mm">{{{{fig:{k}}}}}</div>'
def row(f, t): return f'<div class="jrow">{f}<div class="jtx">{t}</div></div>'
def ul(*xs): return '<ul class="jl">' + ''.join(f'<li>{x}</li>' for x in xs) + '</ul>'
def q(n, body): return f'<div class="jq"><span class="qn">{n}</span><div>{body}</div></div>'
def tip(t, body): return f'<div class="jtip"><b class="t">{t}</b>{body}</div>'
def table(head, rows, cls=''):
    h = ''.join(f'<th>{x}</th>' for x in head)
    b = ''.join('<tr>' + ''.join(f'<th>{c}</th>' if i == 0 else f'<td>{c}</td>' for i, c in enumerate(r)) + '</tr>' for r in rows)
    return f'<table class="jt {cls}"><tr>{h}</tr>{b}</table>'
def flow(*boxes):
    out = []
    for i, (h, t) in enumerate(boxes):
        if i: out.append('<span>→</span>')
        out.append(f'<div><b class="h">{h}</b>{t}</div>')
    return '<div class="jflow">' + ''.join(out) + '</div>'

