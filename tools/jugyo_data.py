def ind_bars():
    rows = [('ア', [21, 13, 40, 16, 10]), ('イ', [9, 69, 7, 5, 10]), ('ウ', [9, 49, 18, 12, 12]), ('エ', [21, 38, 16, 11, 14])]
    names = ['金属', '機械', '化学', '食料品', 'その他']
    cols = ['#9cbad8', '#e9a98b', '#c8b4dc', '#a9cf90', '#f1ede4']
    W, x0, bw, bh, gap, y0 = 600, 40, 548, 30, 12, 34
    s = f'<text x="{W/2}" y="18" font-size="15" font-weight="700" text-anchor="middle">主な工業地帯・地域の製造品出荷額の割合</text>'
    for r, (lab, v) in enumerate(rows):
        y = y0 + r * (bh + gap); x = x0
        s += f'<text x="{x0-10}" y="{y+bh/2+6}" font-size="17" font-weight="700" text-anchor="end">{lab}</text>'
        for k, p in enumerate(v):
            w = bw * p / 100
            s += f'<rect x="{x:.1f}" y="{y}" width="{w:.1f}" height="{bh}" fill="{cols[k]}" stroke="#555" stroke-width=".8"/>'
            t = f'{names[k]} {p}%' if w > 80 else f'{p}%'
            s += f'<text x="{x+w/2:.1f}" y="{y+bh/2+5}" font-size="13" font-weight="700" text-anchor="middle">{t}</text>'
            x += w
    H = y0 + 4 * (bh + gap) + 8
    s += f'<text x="{W-4}" y="{H-6}" font-size="11" fill="#555" text-anchor="end">2019年。工業統計をもとにしたおおよその割合</text>'
    return f'<div class="fig" style="width:150mm;align-self:center"><svg viewBox="0 0 {W} {H}" xmlns="http://www.w3.org/2000/svg">{s}</svg></div>'

